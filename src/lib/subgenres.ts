// Порядок подкатегорий в фильтре «Поиска». Плоский список, а не карта по жанрам:
// поджанры у двух жанров частично пересекаются («Роман», «Драма»), и держать один
// общий список проще, чем два синхронных. Всё, чего тут нет, уходит в конец по алфавиту.
export const SUBGENRE_ORDER = [
  'Роман',
  'Повесть',
  'Рассказы',
  'Приключения',
  'Фантастика',
  'Детектив',
  'Проза',
  'Поэзия и поэмы',
  'Драма',
  'Сказки',
  'Сказки и предания',
  'Пословицы и поговорки',
  'Мировая классика',
]

const rank = (s: string) => {
  const i = SUBGENRE_ORDER.indexOf(s)
  return i < 0 ? SUBGENRE_ORDER.length : i
}

export function sortSubgenres(names: string[]): string[] {
  return [...names].sort((a, b) => rank(a) - rank(b) || a.localeCompare(b, 'ru'))
}
